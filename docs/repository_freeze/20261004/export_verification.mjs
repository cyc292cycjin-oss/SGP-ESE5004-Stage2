import fs from 'node:fs/promises';
import { Workbook } from '@oai/artifact-tool';
const root=new URL('.',import.meta.url);
const rows=JSON.parse(await fs.readFile(new URL('evidence/REMOTE_VERIFICATION_ROWS.json',root),'utf8'));
const fields=['LocalRef','RemoteRef','ExpectedSHA','FetchedSHA','Match','Purpose'];
if(rows.length!==12 || rows.some(r=>!r.Match||r.ExpectedSHA!==r.FetchedSHA))throw Error('Verification evidence does not pass');
const wb=Workbook.create();const sh=wb.worksheets.add('Remote refs');sh.showGridLines=false;
const values=[fields,...rows.map(r=>fields.map(f=>r[f]))];
const range=sh.getRange(`A1:F${values.length}`);range.values=values;
if(JSON.stringify(range.values)!==JSON.stringify(values))throw Error('Typed roundtrip mismatch');
range.format.font={name:'Arial',size:10};range.format.verticalAlignment='center';range.format.wrapText=true;
range.format.rowHeight=72;
sh.getRange('A1:B13').format.columnWidth=43;sh.getRange('C1:D13').format.columnWidth=49;
sh.getRange('E1:E13').format.columnWidth=9;sh.getRange('F1:F13').format.columnWidth=56;
sh.getRange('A1:F1').format.font={name:'Arial',size:10,bold:true};sh.getRange('A1:F1').format.rowHeight=26;
wb.recalculate();
const inspect=await wb.inspect({kind:'table',range:'Remote refs!A1:F4',include:'values',tableMaxRows:4,tableMaxCols:6,maxChars:2000});
const errors=await wb.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!',options:{useRegex:true,maxResults:20},maxChars:500});
await fs.mkdir(new URL('evidence/previews/',root),{recursive:true});
const preview=await wb.render({sheetName:'Remote refs',range:'A1:F5',scale:1,format:'png'});
await fs.writeFile(new URL('evidence/previews/REMOTE_REF_VERIFICATION.png',root),new Uint8Array(await preview.arrayBuffer()));
const quote=x=>'"'+String(x??'').replaceAll('"','""')+'"';
await fs.writeFile(new URL('REMOTE_REF_VERIFICATION.csv',root),'\uFEFF'+range.values.map(r=>r.map(quote).join(',')).join('\r\n')+'\r\n','utf8');
await fs.writeFile(new URL('evidence/TABLE_EXPORT_RECEIPT.json',root),JSON.stringify({rows:rows.length,columns:fields.length,authoring:'@oai/artifact-tool',typed_roundtrip:true,all_equal:true,inspect:inspect.ndjson,error_scan:errors.ndjson},null,2));
console.log(JSON.stringify({rows:rows.length,all_equal:true,exported:'REMOTE_REF_VERIFICATION.csv'}));
