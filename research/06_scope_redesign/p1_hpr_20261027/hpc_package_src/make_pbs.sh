#!/bin/bash
# HPR (RUN_PLAN_HPC.md sections 2-3, 9): generate the PBS Pro job scripts of the HPC package from the REGISTERED values of scripts_project/b4_batch4.py
# (python scripts_project/b4_batch4.py hpc-plan: queue, ncpus, mem, walltime, mode, run id, dependency, WAIT_START_OF per job). No parameter of a
# job is typed here: everything comes from the registration (single source), so the generated scripts cannot drift from RUN_PLAN_HPC.md.
#   bash hpc/make_pbs.sh [out dir]        default out dir: <package>/pbs ; REPO = <package>/repo (unpacked code) or the repository this script sits in
# Generated: pbs/hpr_f1.pbs, hpr_f2.pbs, hpr_batch.pbs (formal; RUN_PLAN_HPC 3), hpr_smoke56.pbs (step D), hpr_build_only_f1.pbs (step D2), hpr_install.pbs
# (step C). Each job script exports JOB_* and runs hpc/hpr_job.sh (or hpc/hpr_install_env.sh) from PBS_O_WORKDIR = the package folder on /hpctmp.
# The user's authorisation text is read by the job body from HPR_AUTH (environment) or <package>/HPR_AUTH.txt (written by hpr_submit.sh); nothing of
# the licence, the account or any host is written into the scripts.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"; PKG="$(cd "$HERE/.." && pwd)"; OUT=${1:-$PKG/pbs}
if [ -n "${REPO:-}" ]; then :; elif [ -f "$PKG/repo/scripts_project/b4_batch4.py" ]; then REPO=$PKG/repo
elif [ -f "$HERE/../../../../scripts_project/b4_batch4.py" ]; then REPO="$(cd "$HERE/../../../.." && pwd)"
else echo "REPO not found (unpacked code ./repo or the repository root); set REPO=<path>"; exit 2; fi
PY=${PY:-$HOME/miniforge3/envs/pypsa-earth/bin/python}; [ -x "$PY" ] || PY=$(command -v python3 || command -v python)
mkdir -p "$OUT"
PLAN=$(cd "$REPO" && "$PY" scripts_project/b4_batch4.py hpc-plan) || { echo "hpc-plan failed"; exit 2; }
COMMIT=$(cat "$PKG/COMMIT" 2>/dev/null || git -C "$REPO" rev-parse HEAD 2>/dev/null || echo unknown)
IFS='|' read -r _ TL WALL GAP WMAX _ < <(echo "$PLAN" | grep '^LIMITS|')
STAMP=$(date -u +%Y-%m-%dT%H:%M:%SZ)
n=0
while IFS='|' read -r _ key name queue ncpus mem wall mode rid depends wait_of; do
  f="$OUT/$name.pbs"
  body="hpc/hpr_job.sh"; [ "$mode" = install ] && body="hpc/hpr_install_env.sh"
  {
    echo "#!/bin/bash"
    echo "#PBS -N $name"
    echo "#PBS -q $queue"
    echo "#PBS -l select=1:ncpus=$ncpus:mem=${mem}gb"
    echo "#PBS -l walltime=$wall"
    echo "#PBS -j oe"
    echo "#PBS -S /bin/bash"
    echo "# HPR job script generated by hpc/make_pbs.sh at $STAMP from scripts_project/b4_batch4.py hpc-plan (RUN_PLAN_HPC.md sections 2-3, 9); package commit $COMMIT."
    echo "# Submit from the package folder on scratch (/hpctmp/<user>/hpr): the formal jobs through hpc/hpr_submit.sh (dependencies $depends), the test jobs with qsub pbs/$name.pbs."
    echo "# The licence is referenced only through GRB_LICENSE_FILE=\$HOME/.gurobi/gurobi.lic (mode 600, placed by the user); never copied, printed or logged."
    echo "export JOB_KEY=$key JOB_NAME=$name JOB_MODE=$mode JOB_RID=$rid JOB_QUEUE=$queue JOB_NCPUS=$ncpus JOB_MEM_GB=$mem JOB_WALLTIME=$wall JOB_TIME_LIMIT_S=$TL JOB_WALL_CAP_S=$WALL JOB_LICENCE_GAP_S=$GAP JOB_WAIT_START_OF=$wait_of JOB_DEPENDS=$depends"
    echo 'cd "${PBS_O_WORKDIR:?submit with qsub from the package folder (or set PBS_O_WORKDIR for the local drill)}" || exit 2'
    if [ "$mode" = smoke56 ]; then
      echo '# the smoke runs the three job bodies in sequence in one job: F1, F2 (56 snapshots each, >= 330 s apart), then the batch-level body (RUN_PLAN_HPC 9)'
      echo 'for rid in F1 F2 batch; do JOB_RID=$rid bash hpc/hpr_job.sh || exit $?; done'
    else
      echo "exec bash $body"
    fi
  } > "$f"
  chmod 755 "$f"; n=$((n + 1))
  echo "$f  queue=$queue ncpus=$ncpus mem=${mem}gb walltime=$wall mode=$mode rid=$rid depends=${depends:-none} wait_start_of=${wait_of:-none}"
done < <(echo "$PLAN" | grep '^JOB|')
echo "$PLAN" > "$OUT/HPC_PLAN.txt"
echo "generated $n job scripts in $OUT (TimeLimit $TL s, wall cap $WALL s, licence gap $GAP s, wait-start max $WMAX s; commit $COMMIT)"
