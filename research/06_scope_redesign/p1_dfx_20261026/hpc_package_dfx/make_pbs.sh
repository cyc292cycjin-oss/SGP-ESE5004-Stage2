#!/bin/bash
# DFX phase 2 (PROPOSED, offline draft): generate the PBS Pro job scripts of the HPC package from parameters (NUS Atlas facts: HPC_FACTS_20261026.md).
#   bash make_pbs.sh [out dir]            default out dir: ./pbs (next to this script)
# Parameters (environment; defaults = HPC_FACTS suggestions, every one to be confirmed by the user on the cluster):
#   QUEUE=parallel          PBS queue (parallel: <= 540 GB, 12-96 cores, <= 720 h; per user <= 8 jobs / 96 cores)
#   NCPUS_BOTH=96           single job running F1 + F2 (run_batch4.sh decides parallel / serial with the P1 probe)
#   NCPUS_ONE=48            each of the two per-run jobs
#   MEM_GB_BOTH=210         single-job memory (serial F1 -> F2: F1 Gurobi process high estimate 160 GiB x 1.3; parallel needs ~400 GB: see README section 3)
#   MEM_GB_F1=210 MEM_GB_F2=200   per-run jobs (B4P estimates 160 / 149 GiB x 1.3)
#   TIME_LIMIT_S=432000     Gurobi TimeLimit (120 h) used for the walltime arithmetic and the smoke job only - the batch runner takes its registered value (README section 5)
#   OVERHEAD_H=5            per run outside the TimeLimit (process 1 ~0.5 h, process 3 ~3 h, post-processing ~1.5 h); walltime = TimeLimit + 2 x overhead
#   PROJECT=                optional "#PBS -P <project>" (not required on this cluster at the time of the facts)
#   HPCTMP=/hpctmp/$USER    scratch root (500 GB, no backup, 60-day purge)
# The job bodies (hpc_job_both.sh, hpc_run_one.sh, hpc_batch_post.sh, hpc_smoke_56.sh) read JOB_* variables exported by the generated scripts and
# the user's authorisation text from DFX_AUTH (qsub -v DFX_AUTH="<text>"); nothing of the licence, account or host is written anywhere.
set -eu
HERE="$(cd "$(dirname "$0")" && pwd)"; OUT=${1:-$HERE/pbs}; mkdir -p "$OUT"
QUEUE=${QUEUE:-parallel}; NCPUS_BOTH=${NCPUS_BOTH:-96}; NCPUS_ONE=${NCPUS_ONE:-48}; MEM_GB_BOTH=${MEM_GB_BOTH:-210}; MEM_GB_F1=${MEM_GB_F1:-210}; MEM_GB_F2=${MEM_GB_F2:-200}
TIME_LIMIT_S=${TIME_LIMIT_S:-432000}; OVERHEAD_H=${OVERHEAD_H:-5}; PROJECT=${PROJECT:-}; HPCTMP=${HPCTMP:-/hpctmp/\$USER}
TL_H=$(( (TIME_LIMIT_S + 3599) / 3600 )); ONE_H=$(( TL_H + 2 * OVERHEAD_H )); BOTH_H=$(( 2 * ONE_H ))
[ $BOTH_H -le 720 ] && [ $ONE_H -le 720 ] || { echo "walltime exceeds the 720 h queue limit (TIME_LIMIT_S=$TIME_LIMIT_S)"; exit 2; }
P_LINE=""; [ -n "$PROJECT" ] && P_LINE="#PBS -P $PROJECT"
gen() {   # $1 file $2 job name $3 ncpus $4 mem GB $5 walltime HH:MM:SS $6 body script $7 extra exports
  cat > "$OUT/$1" <<EOF
#!/bin/bash
#PBS -N $2
#PBS -q $QUEUE
#PBS -l select=1:ncpus=$3:mem=${4}gb
#PBS -l walltime=$5
#PBS -j oe
$P_LINE
# DFX phase 2 draft (generated by make_pbs.sh $(date -u +%Y-%m-%dT%H:%M:%SZ); parameters: queue $QUEUE, ncpus $3, mem $4 GB, walltime $5).
# Submit from the package folder on scratch: cd $HPCTMP/dfx_hpc/package && qsub -v DFX_AUTH="<user authorisation text>" pbs/$1
# The licence is read only through GRB_LICENSE_FILE=\$HOME/.gurobi/gurobi.lic (mode 600); never copied, printed or logged.
export JOB_NCPUS=$3 JOB_MEM_GB=$4 JOB_WALLTIME=$5 JOB_TIME_LIMIT_S=$TIME_LIMIT_S $7
cd "\$PBS_O_WORKDIR" || exit 2
bash "\$PBS_O_WORKDIR/hpc/$6"
EOF
  echo "$OUT/$1  ncpus=$3 mem=${4}gb walltime=$5 -> $6"
}
gen dfx_f12_both.pbs dfx_f12_both "$NCPUS_BOTH" "$MEM_GB_BOTH" "$(printf '%d:00:00' "$BOTH_H")" hpc_job_both.sh ""
gen dfx_f1_integrated.pbs dfx_f1 "$NCPUS_ONE" "$MEM_GB_F1" "$(printf '%d:00:00' "$ONE_H")" hpc_run_one.sh "JOB_RID=F1"
gen dfx_f2_disconnected.pbs dfx_f2 "$NCPUS_ONE" "$MEM_GB_F2" "$(printf '%d:00:00' "$ONE_H")" hpc_run_one.sh "JOB_RID=F2"
gen dfx_batch_post.pbs dfx_post 8 120 08:00:00 hpc_batch_post.sh ""
gen dfx_smoke_56.pbs dfx_smoke 16 24 03:00:00 hpc_smoke_56.sh ""
echo "TimeLimit $TIME_LIMIT_S s = $TL_H h; per-run walltime $ONE_H h; single-job walltime $BOTH_H h (queue limit 720 h)"
